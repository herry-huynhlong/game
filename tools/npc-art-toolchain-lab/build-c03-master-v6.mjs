// Convert each row-run to explicit pixel points; retain hand-authored palette runs in source JSON.
const frames = maps.map(({tag,layers}) => ({
  label: tag,
  durationMs: 1000,
  layers: Object.entries(layers).map(([name,runs])=>{
    const ops=[];
    for(const [y,x,row] of runs){
      for(let i=0;i<row.length;i++){
        const c=row[i]; if(c==='.') continue;
        const names={1:'hair',2:'hairLight',3:'robe',4:'ivory',5:'skinShadow',6:'skin',7:'skinLight',8:'robeLight',9:'brow',A:'gold',B:'eye',C:'shoe',D:'shoeLight',E:'robeDeep',F:'ivoryShade'};
        const key=names[c]; if(!key) throw new Error(`Unknown map pixel ${c} in ${tag}/${name}`);
        ops.push([x+i,y,palette[key]]);
      }
    }
    return {name,ops:[{type:'pixels',points:ops.map(([x,y])=>[x,y]),color:'#FFFFFF'}]};
  })
}));

