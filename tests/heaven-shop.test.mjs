import assert from 'node:assert/strict';
import { build } from 'esbuild';

const bundle = await build({entryPoints:['src/world/HeavenShop.js'],bundle:true,write:false,format:'esm',platform:'node'});
const shop = await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const { buyHeavenItem, giftHeavenItem, learnHeavenBook, commitHeavenChange, rodEquipped } = shop;
const item = 'book_qingyun_wave';
const npc = {id:'recipient',name:'Đệ tử',realmIndex:0,realmLevel:1,alive:true,inventory:[]};
const other = {id:'other',name:'Người khác',alive:true,inventory:[]};
const world = {heaven:{divinePower:30},npcs:[npc,other]};
assert.equal(buyHeavenItem(world,item,'transaction').ok,true);
assert.equal(buyHeavenItem(world,item,'transaction').ok,false);
assert.equal(buyHeavenItem(world,item,'double-click').ok,false);
assert.equal(world.heaven.divinePower,24);
assert.equal(giftHeavenItem(world,'transaction',npc).ok,true);
assert.equal(giftHeavenItem(world,'transaction',other).ok,false);
assert.equal(other.inventory.length,0);
assert.equal(learnHeavenBook(world,npc,item).ok,false);
world.heaven.possession={npcId:npc.id};
assert.equal(learnHeavenBook(world,npc,item).ok,false);
assert.equal(npc.inventory[0].count,1);
npc.realmLevel=2;
assert.equal(commitHeavenChange({populationWorld:world,persistPopulation:()=>false},npc,()=>learnHeavenBook(world,npc,item)).ok,false);
assert.equal(npc.inventory[0].count,1);
assert.equal(world.heaven.shopLedger[0].owner,npc.id);
assert.equal(learnHeavenBook(world,npc,item).ok,true);
assert.equal(npc.inventory.length,0);
const copied = JSON.parse(JSON.stringify(world));
assert.deepEqual(copied.npcs[0].skills,['qingyun_wave']);
assert.equal(copied.heaven.shopLedger[0].owner,'consumed');
const loaded = copied.npcs[0];
loaded.inventory.push({itemId:item,count:1});
assert.equal(learnHeavenBook(copied,loaded,item).ok,false);
assert.equal(loaded.inventory[0].count,1);
assert.equal(rodEquipped({...npc,equippedWeapon:'fishing_rod_basic'}),false);
console.log('PASS: duplicate purchase and gift, required realm, failed-save rollback, permanent learned skill, and rod ownership.');
